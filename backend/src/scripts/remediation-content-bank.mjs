/**
 * Get the content bank for a given subject + topic.
 * Returns null if no real content is available (caller must mark NEEDS_MANUAL_REVIEW).
 */
export function getContentBank(subject, topic) {
  const subjectBank = REMEDIATION_CONTENT_BANK[subject];
  if (!subjectBank) return null;
  return subjectBank[topic] ?? null;
}

/**
 * Pick a real question from the bank for the given index, cycling through
 * the authored questions so each remediated document gets real content.
 */
export function pickRealQuestion(subject, topic, index) {
  const bank = getContentBank(subject, topic);
  if (!bank || bank.length === 0) return null;
  return bank[index % bank.length];
}
